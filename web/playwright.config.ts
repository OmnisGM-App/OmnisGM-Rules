import { defineConfig, devices } from '@playwright/test';
// Порт — от слота (Table#469): соседний worktree берёт OMNISGM_SLOT=1 и не мешает этому.
import { E2E_PORT as PORT, BASE_URL as BASE } from './e2e/ports';
import { NARROW_MAX } from './e2e/viewport';

// Спеки проекта `mobile`. Список ЯВНЫЙ, а не маска: маска затянула бы визуальные снапшоты и
// весь набор целиком, удвоив прогон без единой новой находки (#286).
//
// Состав честно смешанный, и это стоит знать: `reader`, `lang` и навигационная часть
// `doc-hub` действительно перестраиваются по ширине, а `404` от ширины не зависит вовсе
// (страница 404 не использует ReaderShell) — он здесь только затем, чтобы «страница не
// найдена» проверялась и в мобильном Chromium: это самый частый вход из выдачи по мёртвой
// ссылке. На WebKit-смоук членство в этом списке НЕ влияет никак — тот проект отбирает
// тесты одним лишь `grep` (ревью #300). В `doc-hub` заодно едут проверки
// canonical/hreflang/sitemap и JSON-LD, которые от ширины не зависят: цена — несколько
// секунд, зато файл не приходится дробить (ревью #302).
const MOBILE_SPECS = [
  /reader\.spec\.ts/,
  /doc-hub\.spec\.ts/,
  /lang\.spec\.ts/,
  /404\.spec\.ts/,
  // Тач-ввод и свёрнутые контролы бара (#308) — единственный спек, который на десктопе
  // проверять нечего: обе его ветки там недостижимы и сами себя пропускают.
  /mobile-controls\.spec\.ts/,
];

// Мобильный вьюпорт один на оба новых проекта и совпадает с уже принятой в репозитории
// шириной (`visual.spec.ts`, `layout-stability.spec.ts` — 390×844). Дескрипторы устройств
// дают РАЗНОЕ (Pixel 7 — 412×839, iPhone 14 — 390×664), и «тот же вьюпорт» было бы
// неправдой, а сравнивать движки на разной ширине — сравнивать не движки (ревью #302).
const MOBILE_VIEWPORT = { width: 390, height: 844 };

// Вьюпорт обязан попадать в мобильную ветку `isNarrow()`, иначе проекты `mobile` и
// `webkit-mobile` останутся зелёными, проверяя ДЕСКТОПНУЮ раскладку: подними порог в
// reader.css — и связи между двумя литералами не заметит никто (ревью #300). Падаем на
// загрузке конфига, до первого теста.
if (MOBILE_VIEWPORT.width > NARROW_MAX) {
  throw new Error(`Мобильный вьюпорт ${MOBILE_VIEWPORT.width}px шире порога узкой ` +
                  `раскладки ${NARROW_MAX}px — проекты mobile/webkit-mobile проверяли бы десктоп`);
}

// E2E гоняются ЛОКАЛЬНО (npm run test:e2e), в CI не тащим — там только astro check + build.
// Тестируем прод-вывод: собираем бандл и поднимаем `astro preview` (ровно то, что уедет
// на хостинг), а не dev-сервер.
export default defineConfig({
  testDir: './e2e',
  // Страж чужого preview на нашем порту — см. комментарий в самом файле.
  globalSetup: './e2e/global-setup.ts',
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  retries: 0,
  reporter: 'list',
  use: {
    baseURL: BASE,
    trace: 'on-first-retry',
  },
  // Визуальные снапшоты (e2e/visual.spec.ts): небольшой допуск под сглаживание.
  // Baseline привязаны к платформе (…-darwin.png) — гоняем локально на одной машине,
  // кросс-ОС расхождений нет (в CI e2e не запускаем). Обновление:
  //   rm -r node_modules/.vite && npm run test:e2e -- visual --update-snapshots
  expect: {
    // maxDiffPixels (абсолют), а НЕ maxDiffPixelRatio: небольшое цветовое изменение
    // (напр. цвет ссылок ~2000 пикс.) — это <1% полной страницы, и ratio 0.01 такое
    // «проглатывал» (снапшот не ловил регрессию и не обновлялся). Абсолютный порог
    // терпит AA-джиттер шрифтов, но ловит реальные правки.
    toHaveScreenshot: { maxDiffPixels: 80, animations: 'disabled' },
  },
  projects: [
    // Основной набор: десктопный Chromium, все спеки, включая пиксельные снапшоты.
    { name: 'chromium', use: { ...devices['Desktop Chrome'] } },
    // Мобильный вьюпорт (#286). Ридер — публичная страница, телефон у неё основной носитель,
    // а до сих пор мобильную вёрстку трогали два спека из 35, каждый своим `setViewportSize`.
    //
    // Гоняем НЕ ВЕСЬ набор, и это осознанно (урок Table#377): вторая полная матрица удваивает
    // время и приносит те же падения дважды. Состав — в комментарии у `MOBILE_SPECS` выше,
    // там же честно про то, что список смешанный; дублировать объяснение здесь не нужно —
    // два текста об одном составе разъезжаются, что уже и произошло (ревью #302).
    {
      name: 'mobile',
      testMatch: MOBILE_SPECS,
      use: { ...devices['Pixel 7'], viewport: MOBILE_VIEWPORT },
    },
    // WebKit (движок Safari) на том же вьюпорте, что и `mobile`, — смоук, а не матрица: только тесты с
    // тегом @cross-engine. Пиксельные снапшоты пропускаем — кросс-движковой пиксель-парити
    // не существует (шрифты и сглаживание рендерятся иначе), сравнение шло бы движка с
    // самим собой.
    //
    // ВАЖНО и проверено на своей шкуре: Playwright-WebKit НЕ ловит квирки НАТИВНЫХ контролов
    // Safari — там был ложный зелёный на сломанном <select>. Этот проект закрывает движок
    // (раскладка, поддержка CSS/JS), а не браузер; ручной смоук в Safari он не отменяет.
    {
      name: 'webkit-mobile',
      // Только `grep`, без `testMatch`: они работают КОНЪЮНКТИВНО, и тег, поставленный на
      // тест вне MOBILE_SPECS, молча не запускался бы — Playwright не считает ошибкой
      // пустой набор у отдельного проекта. А расширение этого проекта задумано именно
      // тегированием, значит тег и обязан быть единственным источником состава (ревью #302).
      grep: /@cross-engine/,
      ignoreSnapshots: true,
      use: { ...devices['iPhone 14'], viewport: MOBILE_VIEWPORT },
    },
  ],
  webServer: {
    command: `npm run build && npm run preview -- --port ${PORT}`,
    url: BASE,
    reuseExistingServer: !process.env.CI,
    timeout: 120_000,
  },
});
