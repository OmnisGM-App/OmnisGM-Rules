/**
 * Порты прогона — от «слота» (Table#469).
 *
 * Одна машина, два рабочих каталога: соседний worktree того же репозитория гоняет свои e2e
 * и обязан не мешать. Мешает он двумя способами. Явный — занятый порт: второй прогон просто
 * не поднимет preview. Тихий и куда хуже — `reuseExistingServer`: Playwright молча цепляется
 * к ЧУЖОМУ preview, и вся матрица идёт против чужой ветки. Выглядит это как настоящая
 * регрессия (в Table такое ловили дважды, там же и завели стража — Table#345).
 *
 * Слот — целое число, из которого выводятся все порты продукта. Слот 0 отдаёт привычные
 * значения, поэтому основной каталог, README и адреса в закладках не меняются; соседнему
 * worktree достаточно `OMNISGM_SLOT=1`.
 *
 * Шаг 10, а не 1: между продуктами экосистемы порты разведены сотнями (у News свой блок),
 * и десятка внутри продукта оставляет запас на будущие сервисы, не наезжая на соседний блок.
 */

/** Потолок слота. Выше — начнут пересекаться блоки соседних продуктов (см. шаг 10 выше). */
const MAX_SLOT = 3;

export function slot(): number {
  const raw = process.env.OMNISGM_SLOT;
  if (raw === undefined || raw === '') return 0;

  const value = Number(raw);
  if (!Number.isInteger(value) || value < 0 || value > MAX_SLOT) {
    throw new Error(
      `OMNISGM_SLOT=${raw} — ожидалось целое от 0 до ${MAX_SLOT}. `
      + 'Слот разводит порты параллельных прогонов: 0 — основной каталог, 1 и дальше — соседние worktree.',
    );
  }
  return value;
}

/** Порт `astro preview`, против которого идут e2e. */
export const PORT = 4321 + slot() * 10;

export const BASE_URL = `http://localhost:${PORT}`;
