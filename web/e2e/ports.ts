import { ports } from '@omnisgm-app/core/blocks';
import { slot } from '@omnisgm-app/core/ports';

/**
 * Порты прогона — от «слота» (Table#469).
 *
 * Одна машина, два рабочих каталога: соседний worktree того же репозитория гоняет свои e2e
 * и обязан не мешать. Мешает он двумя способами. Явный — занятый порт: второй прогон просто
 * не поднимет preview. Тихий и куда хуже — `reuseExistingServer`: Playwright молча цепляется
 * к ЧУЖОМУ preview, и вся матрица идёт против чужой ветки. Выглядит это как настоящая
 * регрессия (в Table такое ловили дважды, там же и завели стража — Table#345).
 *
 * Слот — целое число, из которого выводятся все порты продукта. Слот 0 отдаёт привычные
 * значения, поэтому основной каталог, README и адреса в закладках не меняются; соседнему
 * worktree достаточно `OMNISGM_SLOT=1`.
 *
 * Шаг 10, а не 1: десятка оставляет запас на будущие сервисы продукта. «Разнос сотнями»
 * между продуктами — верно не везде: e2e-порт News (4319 + слот × 10) стоит в двух шагах от
 * нашего preview, и окно 4321–4330 уже содержит чужой 4329. Пересечений при слотах 0–3 нет
 * (наши 4321/4331/4341/4351 против их 4319/4329/4339/4349), но держится это на конкретных
 * числах, а не на «сотнях».
 *
 * ИМЕННО ПОЭТОМУ разбор слота и карта баз всей экосистемы уехали в `@omnisgm-app/core`
 * (Table#477). Раньше проверку пересечений вели копиями списков в каждом продукте — а у нас
 * её не было вовсе: соседи сверялись со списком из двух наших портов, мы не сверялись ни с
 * чем. Теперь карта одна, и её тест обходит четыре блока по всем слотам целиком, так что
 * «в двух шагах от чужого порта» — проверяемое утверждение, а не расчёт в комментарии.
 *
 * ЧТО ОСТАЛОСЬ ЗДЕСЬ: имена, под которыми порты знает Rules, и `BASE_URL`.
 */

/** Блок Rules: preview и dev. Базы и сдвиг — из общей карты экосистемы. */
const rules = ports('rules');

/**
 * Слот наружу — часть публичного API модуля портов продукта: соседние скрипты берут его
 * оттуда же, откуда порты, и второго способа узнать слот заводить не нужно.
 */
export { slot };

/** Порт `astro preview`, против которого идут e2e. */
export const E2E_PORT = rules.e2e;

/**
 * Порт `npm run dev`. Отдельная база, а не тот же `E2E_PORT`: dev-сервер и preview — РАЗНЫЕ
 * серверы (e2e идут против прод-сборки), и посадив их на один порт, мы бы узаконили как раз
 * то, от чего защищает страж, — молчаливый прогон матрицы против dev-сервера.
 */
export const DEV_PORT = rules.dev;

export const BASE_URL = `http://localhost:${E2E_PORT}`;
