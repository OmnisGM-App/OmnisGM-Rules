import type { Page } from '@playwright/test';

/**
 * Ширина, ниже которой ридер перестраивается в мобильную раскладку.
 *
 * Число не выдумано и не округлено: это ровно тот `@media (max-width: 820px)` из
 * `src/styles/reader.css`, внутри которого прячется боковое дерево (`.rd-nav`), появляется
 * кнопка «Разделы» (`.rd-act-nav`), вкладки систем сменяются `<select>`, а языковая пара —
 * `.rd-lang-sel`. Литерал 900, стоявший в спеках до ревью #302, не встречался в CSS вовсе и
 * давал зазор 821–899: `iPad Pro 11` portrait — 834, то есть устройство, ради которого порог
 * и поднимали до 820, тест классифицировал бы как десктоп.
 */
export const NARROW_MAX = 820;

/** Узкая ли раскладка у страницы — по её фактическому вьюпорту. */
export const isNarrow = (page: Page) => (page.viewportSize()?.width ?? 0) <= NARROW_MAX;
