// Согласование числительного с существительным (issue #240).
//
// Русский требует три формы («1 монстр», «2 монстра», «5 монстров»), и без них хабы писали
// «Все 1 животных» и «Все 24 заговоров» — текст, который читается как машинный перевод.
// После #214 эта же строка стала началом сниппета, то есть ошибка видна прямо в выдаче.
//
// Формы задаёт вызывающий: вывести их из слова нельзя (род, одушевлённость, чередования),
// а таблица исключений в библиотеке была бы больше самого списка наших сущностей.

/** Выбор формы по числу: [именительный ед., форма при 2–4, форма при 5+]. */
export function pluralRu(n, [one, few, many]) {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/**
 * Начало фразы хаба: «Все 5 монстров» / «All 5 monsters», но при одной сущности — без «Все»:
 * «1 животное» / «1 animal». «Все 1 животное» неестественно даже с верным склонением, а
 * «Единственное животное» потребовало бы знать род — лишнее знание в каждом шаблоне.
 */
export function countPhrase(n, lang, ru, en) {
  if (lang === 'ru') {
    const word = pluralRu(n, ru);
    // «Все» согласуется только с множественным: «Все 21 животное» ломается ровно так же,
    // как «Все 1 животных», — при 1, 21, 101 существительное встаёт в единственное число.
    return word === ru[0] ? `${n} ${word}` : `Все ${n} ${word}`;
  }
  const word = n === 1 ? en[0] : en[1];
  return n === 1 ? `1 ${word}` : `All ${n} ${word}`;
}

/**
 * Английский проще: форм две, но существительное в наших шаблонах стоит НЕ рядом с числом
 * («All 339 D&D 5.2 spells alphabetically») — между ними метка системы. Поэтому число и слово
 * подставляются раздельно: countLeadEn в начало, pluralEn на место существительного.
 *
 * Функция именно английская: RU-строку собирает countPhrase целиком, и «Все» там решается по
 * форме существительного, а не по числу («21 монстр» — без «Все»). Общая функция с параметром
 * языка выглядела бы применимой к RU, но в русских шаблонах не вызывается никогда.
 */
export function countLeadEn(n) {
  return n === 1 ? '1' : `All ${n}`;
}

export function pluralEn(n, [one, many]) {
  return n === 1 ? one : many;
}
